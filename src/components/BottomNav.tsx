export default function BottomNav() {
  const pathname = usePathname()
  const [user, setUser] = useState<User | null>(null)
  const supabase = createClient()

  useEffect(() => {
    supabase.auth.getUser().then(({ data }) => setUser(data.user))
    const { data: { subscription } } = supabase.auth.onAuthStateChange(
      (_, session) => setUser(session?.user ?? null)
    )
    return () => subscription.unsubscribe()
  }, [supabase.auth])

  // Only show bottom nav if user is logged in
  if (!user) return null

  return (
    <nav className="md:hidden fixed bottom-0 left-0 right-0 z-50 bg-elevated border-t border-border">
      <div className="flex items-center justify-around px-2 py-2 safe-area-pb">
        {navItems.map(item => {
          const isActive = pathname === item.href
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex flex-col items-center gap-1 px-3 py-1.5 rounded-xl transition-colors min-w-0 ${
                isActive ? 'text-accent' : 'text-text-tertiary'
              }`}
            >
              {item.icon(isActive)}
              <span className="text-xs font-medium truncate">{item.label}</span>
            </Link>
          )
        })}
      </div>
    </nav>
  )
}